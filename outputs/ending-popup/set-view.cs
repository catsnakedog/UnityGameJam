using System.Reflection;
var assembly = typeof(UnityEditor.Editor).Assembly;
var viewType = assembly.GetType("UnityEditor.GameView");
var view = UnityEditor.EditorWindow.GetWindow(viewType);
var flags = BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic;
var selection = viewType.GetProperty("selectedSizeIndex", flags);
UnityEditor.SessionState.SetInt("EndingPopup.PreviousViewSize", (int)selection.GetValue(view));
var sizesType = assembly.GetType("UnityEditor.GameViewSizes");
var singleton = typeof(UnityEditor.ScriptableSingleton<>).MakeGenericType(sizesType).GetProperty("instance").GetValue(null);
var group = sizesType.GetMethod("GetGroup").Invoke(singleton, new object[] { UnityEditor.GameViewSizeGroupType.Standalone });
var groupType = group.GetType();
int count = (int)groupType.GetMethod("GetTotalCount").Invoke(group,null);
var sizeType = assembly.GetType("UnityEditor.GameViewSize");
var modeType = assembly.GetType("UnityEditor.GameViewSizeType");
var size = Activator.CreateInstance(sizeType, new object[] { Enum.Parse(modeType,"FixedResolution"), 1440, 1080, "Ending Popup QA" });
groupType.GetMethod("AddCustomSize").Invoke(group,new[] { size });
UnityEditor.SessionState.SetInt("EndingPopup.QAViewSize", count);
selection.SetValue(view,count);
view.Repaint();
return new { selected = count, previous = UnityEditor.SessionState.GetInt("EndingPopup.PreviousViewSize",-1) };
