using System;
using System.Collections.Generic;
using System.Text;

namespace GameJam.Data.Editor
{
    public static class DataCodeGenerator
    {
        public const string OutputPath = "Assets/Scripts/Data/Generated/DataTables.cs";

        public static string Generate(IReadOnlyList<DataTable> tables)
        {
            var code = new StringBuilder("// Generated by Tools > Data Manager. Schema only; edit the source CSV.\n");
            code.AppendLine("namespace GameJam.Data.Generated\n{");
            foreach (var table in tables)
            {
                // Separate namespaces prevent collisions between arbitrary table and column names.
                code.AppendLine($"    namespace @{table.Name}\n    {{");
                code.AppendLine("        public static class Table\n        {");
                code.AppendLine($"            public static global::GameJam.Data.DataTable Data => global::GameJam.Data.GameData.GetTable(\"{table.Name}\");");
                code.AppendLine($"            public static Row Get({table.Columns[table.KeyIndex].Type} id) => new Row(Data.Get(id));");
                code.AppendLine("            public static global::System.Collections.Generic.IEnumerable<Row> All\n            {\n                get { foreach (var item in Data.Rows) yield return new Row(item); }\n            }");
                code.AppendLine("        }");
                code.AppendLine("        public readonly struct Row\n        {");
                code.AppendLine("            readonly global::GameJam.Data.DataRow _dataRow;\n            internal Row(global::GameJam.Data.DataRow row) { _dataRow = row; }");
                foreach (var column in table.Columns)
                {
                    if (column.Name == "Row" || column.Name == "_dataRow")
                        throw new FormatException(table.Name + ": column name '" + column.Name + "' is reserved for generated accessors.");
                    string type = DataValue.CSharpType(column.Type);
                    code.AppendLine($"            public {type} @{column.Name} => _dataRow.Get<{type}>(\"{column.Name}\");");
                }
                code.AppendLine("        }\n    }");
            }
            code.AppendLine("}");
            return code.ToString();
        }
    }
}
